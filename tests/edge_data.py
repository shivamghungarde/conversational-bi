def sql_script() -> str:
    q = lambda v: "NULL" if v is None else (str(v) if isinstance(v, (int, float)) else "'" + str(v).replace("'", "''") + "'")
    row = lambda vals: "(" + ", ".join(q(v) for v in vals) + ")"
    lines = [
        "-- Edge-case dataset for the professional_services semantic model. Generated by tests/edge_data.py.",
        "CREATE TABLE employees (employee_id INTEGER PRIMARY KEY, employee_name TEXT, practice TEXT, region TEXT,",
        "                        grade TEXT, bill_rate REAL, cost_rate REAL, start_date TEXT);",
        "CREATE TABLE clients (client_id INTEGER PRIMARY KEY, client_name TEXT, industry TEXT);",
        "CREATE TABLE projects (project_id INTEGER PRIMARY KEY, project_name TEXT, client_id INTEGER, practice TEXT,",
        "                       billing_type TEXT, start_date TEXT, end_date TEXT);",
        "CREATE TABLE timesheets (entry_id INTEGER PRIMARY KEY, work_date TEXT, employee_id INTEGER, project_id INTEGER,",
        "                         available_hours REAL, billable_hours REAL, nonbillable_hours REAL, revenue REAL,",
        "                         cost REAL, submitted_at TEXT);",
        "CREATE TABLE timesheet_backlog AS SELECT * FROM timesheets WHERE 0;",
    ]
    lines += [f"INSERT INTO employees VALUES {row(e)};" for e in EMPLOYEES]
    lines += [f"INSERT INTO clients VALUES {row(c)};" for c in CLIENTS]
    lines += [f"INSERT INTO projects VALUES {row(p)};" for p in PROJECTS]
    for i, (date, eid, pid, avail, billable, revenue, cost) in enumerate(TIMESHEETS, start=1):
        vals = (i, date, eid, pid, avail, billable, avail - billable, revenue, cost, f"{date}T18:00:00")
        lines.append(f"INSERT INTO timesheets VALUES {row(vals)};")
    return "\n".join(lines) + "\n"


def build_sqlite(path: Path) -> Path:
    if path.exists():
        path.unlink()
    con = sqlite3.connect(path)
    con.executescript((OUT / "edge_dataset.sql").read_text(encoding="utf-8"))
    con.commit()
    con.close()
    return path


def money(v: float) -> str:
    """Accounting style, as finance exports do: $1,234.50 and ($500.00) for negatives."""
    s = f"${abs(v):,.2f}"
    return f"({s})" if v < 0 else s


def write_csv(path: Path) -> None:
    import csv
    with open(path, "w", newline="", encoding="utf-8-sig") as fh:  # BOM, like Excel's "CSV UTF-8"
        w = csv.writer(fh)
        w.writerow(["Date", "Consultant", "Practice", "Region", "Grade", "Client", "Available Hours",
                    "Billable Hours", "Revenue ($)"])
        for r in RECORDS:
            d = dt.date.fromisoformat(r["date"])
            w.writerow([d.strftime("%d/%m/%Y"), r["consultant"], r["practice"], r["region"], r["grade"], r["client"],
                        r["available_hours"], r["billable_hours"], money(r["revenue"])])
        w.writerow([])  # trailing blank line


def excel_serial(date: str) -> int:
    return (dt.date.fromisoformat(date) - dt.date(1899, 12, 30)).days


def write_xlsx(path: Path, sheets: list) -> None:
    """Minimal .xlsx writer. `sheets` is [(name, headers, rows)]. Cell values: str, int/float, bool,
    ("date", "YYYY-MM-DD"), ("formula", "A1+B1", cached_value), ("inline", "text") or None (cell omitted)."""
    strings: list = []

    def sidx(v):
        if v not in strings:
            strings.append(v)
        return strings.index(v)

    def col(i):
        s = ""
        i += 1
        while i:
            i, r = divmod(i - 1, 26)
            s = chr(65 + r) + s
        return s

    def cell(ref, v):
        if v is None:
            return ""
        if isinstance(v, bool):
            return f'<c r="{ref}" t="b"><v>{int(v)}</v></c>'
        if isinstance(v, (int, float)):
            return f'<c r="{ref}"><v>{v}</v></c>'
        if isinstance(v, tuple) and v[0] == "date":
            return f'<c r="{ref}" s="1"><v>{excel_serial(v[1])}</v></c>'
        if isinstance(v, tuple) and v[0] == "formula":
            return f'<c r="{ref}"><f>{escape(v[1])}</f><v>{v[2]}</v></c>'
        if isinstance(v, tuple) and v[0] == "inline":
            return f'<c r="{ref}" t="inlineStr"><is><t>{escape(v[1])}</t></is></c>'
        return f'<c r="{ref}" t="s"><v>{sidx(str(v))}</v></c>'

    ns = 'xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"'
    rns = 'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"'
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        sheet_tags, rels = [], []
        for n, (name, headers, rows) in enumerate(sheets, start=1):
            xml_rows = []
            for r_i, values in enumerate([headers] + rows, start=1):
                xml_rows.append(f'<row r="{r_i}">' + "".join(cell(f"{col(c)}{r_i}", v) for c, v in enumerate(values)) + "</row>")
            z.writestr(f"xl/worksheets/sheet{n}.xml", f"<worksheet {ns}><sheetData>{''.join(xml_rows)}</sheetData></worksheet>")
            sheet_tags.append(f'<sheet name="{escape(name)}" sheetId="{n}" r:id="rId{n}"/>')
            rels.append(f'<Relationship Id="rId{n}" Type="worksheet" Target="worksheets/sheet{n}.xml"/>')
        z.writestr("xl/workbook.xml", f"<workbook {ns} {rns}><sheets>{''.join(sheet_tags)}</sheets></workbook>")
        z.writestr("xl/_rels/workbook.xml.rels",
                   '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                   + "".join(rels) + "</Relationships>")
        z.writestr("xl/sharedStrings.xml", f"<sst {ns}>" + "".join(f"<si><t>{escape(s)}</t></si>" for s in strings) + "</sst>")
        z.writestr("xl/styles.xml",
                   f'<styleSheet {ns}><numFmts count="1"><numFmt numFmtId="164" formatCode="dd/mm/yyyy"/></numFmts>'
                   '<cellXfs><xf numFmtId="0"/><xf numFmtId="164"/></cellXfs></styleSheet>')


def write_edge_xlsx(path: Path) -> None:
    headers = ["Date", "Consultant", "Practice", "Region", "Grade", "Client", "Available Hours", "Billable Hours", "Revenue"]
    rows = [[("date", r["date"]), r["consultant"], ("inline", r["practice"]), r["region"], r["grade"], r["client"],
             r["available_hours"], r["billable_hours"], r["revenue"]] for r in RECORDS]
    notes = [["Generated by tests/edge_data.py"], ["The largest sheet is read; this one is ignored."]]
    write_xlsx(path, [("Read me", ["Note"], notes), ("Timesheets", headers, rows)])


