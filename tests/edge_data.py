def records() -> list:
    """The flattened view every source exposes: one dict per timesheet row."""
    emp = {e[0]: e for e in EMPLOYEES}
    proj = {p[0]: p for p in PROJECTS}
    cli = {c[0]: c for c in CLIENTS}
    out = []
    for date, eid, pid, avail, billable, revenue, cost in TIMESHEETS:
        e = emp[eid]
        out.append({
            "date": date, "consultant": e[1], "practice": e[2], "region": e[3], "grade": e[4],
            "client": cli[proj[pid][2]][1] if pid else BENCH,
            "available_hours": avail, "billable_hours": billable, "revenue": revenue,
        })
    return out


